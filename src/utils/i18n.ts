export function t(lang: Language, key: keyof typeof translations['id'], params?: Record<string, string | number>): string {
  let str = (translations[lang] && translations[lang][key]) || translations.id[key] || '';
  if (params) {
    Object.entries(params).forEach(([k, v]) => {
      str = str.replace(`{${k}}`, String(v));
    });
  }
  return str;
}
